pub fn image(i: Icon, size: f32, color: Color32) -> egui::Image<'static> {
    let svg = format!("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\" width=\"96\" height=\"96\"><path fill=\"#ffffff\" d=\"{}\"/></svg>", path(i));
    egui::Image::from_bytes(format!("bytes://icon-{:?}.svg", i), svg.into_bytes()).fit_to_exact_size(Vec2::splat(size)).tint(color)
}

pub fn show(ui: &mut Ui, i: Icon, size: f32, color: Color32) -> Response {
    ui.add(image(i, size, color))
}

/// A round icon button (40 px like the original's icon buttons).
pub fn button(ui: &mut Ui, i: Icon, color: Color32, hover_bg: Color32, tip: &str) -> Response {
    let (rect, resp) = ui.allocate_exact_size(Vec2::splat(36.0), Sense::click());
    if resp.hovered() {
        ui.painter().circle_filled(rect.center(), 18.0, hover_bg);
    }
    image(i, 22.0, color).paint_at(ui, egui::Rect::from_center_size(rect.center(), Vec2::splat(22.0)));
    resp.on_hover_text(tip)
}
